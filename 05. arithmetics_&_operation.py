# Arithmetics & Operations
# + = adding something
# - = subtracting something
# * = multiplying something
# / = dividing something
# % = modulus (remainder of a division)
# ** = exponentiation (power)
# // = floor division (division that rounds down to the nearest whole number)

# Math Functions
# round() = rounds a number to the nearest whole number
# abs() = returns the absolute value of a number (the distance from zero)
# pow() = raises a number to the power of another number
# max() = returns the largest of a set of numbers
# min() = returns the smallest of a set of numbers

#math.pi Functions
# math.sqrt() = returns the square root of a number
# math.pi = a constant that represents the ratio of the circumference of a circle to its diameter (approximately 3.14159)
# math.e = a constant that represents the base of the natural logarithm (approximately 2.71828)
#math.ceil() = rounds a number up to the nearest whole number
# math.floor() = rounds a number down to the nearest whole number
# math.sin() = returns the sine of an angle (in radians)
# math.cos() = returns the cosine of an angle (in radians)
# math.tan() = returns the tangent of an angle (in radians)
# math.log() = returns the natural logarithm of a number
# math.exp() = returns the value of e raised to the power of a number
